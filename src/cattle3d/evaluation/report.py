"""Render study results as Markdown tables, CSV and figures.

Owns: presentation only. Every number in ``reports/`` is written here from a
StudyResult, so reports are regenerated, never hand-edited.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from cattle3d.audit import JoinAudit
from cattle3d.evaluation.stats import metrics
from cattle3d.evaluation.study import (
    ENSEMBLE,
    H3B_MARGIN_MAPE,
    HERD_NAMES,
    MODELS,
    StudyResult,
)


def _md_table(rows: list[dict[str, object]]) -> str:
    if not rows:
        return ""
    cols = list(rows[0])
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in rows:
        lines.append("| " + " | ".join(str(row[c]) for c in cols) + " |")
    return "\n".join(lines)


def _verdict(comparison) -> str:
    if comparison.a_better:
        return "first is better"
    if comparison.b_better:
        return "second is better"
    return "no claimable difference"


def write_oof_csv(result: StudyResult, path: Path) -> None:
    frames = []
    for herd, r in result.herds.items():
        data = {"herd": herd, "animal_id": r.animal_ids, "weight_kg": r.weight_kg}
        data.update({f"oof_{name}": pred for name, pred in r.oof.items()})
        frames.append(pd.DataFrame(data))
    pd.concat(frames).to_csv(path, index=False)


def results_markdown(result: StudyResult) -> str:
    out = [
        "# Results on the two public herds",
        "",
        "Generated by `cattle3d evaluate`. Do not edit by hand.",
        "",
        "Protocol: one row per animal; 5-fold cross-validation repeated with 5 seeds; "
        "LightGBM hyperparameters tuned in an inner 3-fold CV inside each training fold "
        "(nested). Confidence intervals: 10,000 bootstrap resamples of animals. "
        "Paired comparisons use the same animals and the seed-averaged out-of-fold predictions.",
        "",
    ]

    out += ["## Within-herd accuracy", ""]
    for herd, r in result.herds.items():
        rows = []
        for name in MODELS:
            m = metrics(r.weight_kg, r.oof[name])
            rows.append(
                {
                    "model": name,
                    "MAE kg [95% CI]": f"{r.mae_ci[name].estimate:.1f} [{r.mae_ci[name].low:.1f}, {r.mae_ci[name].high:.1f}]",
                    "seed SD": f"{r.seed_mae_sd[name]:.2f}",
                    "MAPE %": f"{m.mape:.2f}",
                    "RMSE": f"{m.rmse:.1f}",
                    "p95 |err|": f"{m.p95_abs:.0f}",
                    "max |err|": f"{m.max_abs:.0f}",
                    "R²": f"{m.r2:.2f}",
                }
            )
        sd = float(np.std(r.weight_kg, ddof=1))
        out += [
            f"### {HERD_NAMES[herd]}: n = {r.n}, weight {r.weight_kg.min():.0f}–{r.weight_kg.max():.0f} kg, SD {sd:.1f} kg",
            "",
            _md_table(rows),
            "",
        ]

    out += [
        "## H1 (supporting): 3-D volume versus manual measurements",
        "",
        "Difference = MAE(second) − MAE(first) in kg. Positive means the first model is better. "
        "Manual model: the same robust linear regressor on withers height, hip height, chest width "
        "and heart girth measured by hand on the same animals. Holm correction over the H1 family.",
        "",
    ]
    rows = []
    for herd, r in result.herds.items():
        for name, c in r.h1.items():
            key = f"{herd}: {name}"
            rows.append(
                {
                    "herd": HERD_NAMES[herd],
                    "comparison": name,
                    "ΔMAE kg [95% CI]": f"{c.mae_difference.estimate:+.2f} [{c.mae_difference.low:+.2f}, {c.mae_difference.high:+.2f}]",
                    "Wilcoxon p": f"{c.wilcoxon_p:.4f}",
                    "Holm p": f"{result.h1_holm[key]:.4f}",
                    "verdict": _verdict(c),
                }
            )
    out += [_md_table(rows), ""]

    out += [
        "## H3 (primary): transfer between herds",
        "",
        "### H3a: zero-shot transfer (no data from the target herd)",
        "",
    ]
    rows = []
    for t in result.transfers:
        yt = result.herds[t.target].weight_kg
        for name, pred in t.zero_shot.items():
            m = metrics(yt, pred)
            b = t.bias_ci[name]
            rows.append(
                {
                    "train → test": f"{t.source} → {t.target}",
                    "model": name,
                    "MAE kg": f"{m.mae:.1f}",
                    "bias kg [95% CI]": f"{b.estimate:+.1f} [{b.low:+.1f}, {b.high:+.1f}]",
                    "|bias| / MAE": f"{abs(m.bias) / m.mae:.2f}",
                    "MAPE %": f"{m.mape:.2f}",
                }
            )
    out += [
        _md_table(rows),
        "",
        "H3a is supported for a model when the bias CI excludes 0 and |bias|/MAE ≥ 0.5.",
        "",
        "### H3b: recalibration with k reference weighings of the new herd",
        "",
        f"Ensemble trained on the source herd, corrected on k random target animals, scored on the "
        f"other target animals (500 draws per k). Margin: recalibrated MAPE at most "
        f"{H3B_MARGIN_MAPE:.1f} point above the target herd's own within-herd CV MAPE. "
        "The bracketed range is the spread over draws, i.e. what one farm could get depending on "
        "which animals it weighs; 'draws within margin' is the share of farms that would meet it.",
        "",
    ]
    rows = []
    for t in result.transfers:
        for p in t.recalibration:
            excess = p.mape_mean - t.within_target_mape
            rows.append(
                {
                    "train → test": f"{t.source} → {t.target}",
                    "correction": p.mode,
                    "k": p.k,
                    "MAE kg [95% range]": f"{p.mae_mean:.1f} [{p.mae_low:.1f}, {p.mae_high:.1f}]",
                    "MAPE % [95% range]": f"{p.mape_mean:.2f} [{p.mape_low:.2f}, {p.mape_high:.2f}]",
                    "within-herd MAPE %": f"{t.within_target_mape:.2f}",
                    "excess MAPE (mean)": f"{excess:+.2f}",
                    "mean within margin": "yes" if excess <= H3B_MARGIN_MAPE else "no",
                    "draws within margin": f"{100 * p.share_within:.0f} %",
                }
            )
    out += [_md_table(rows), ""]

    out += ["### H3c: physics model versus ensemble after transfer", ""]
    rows = []
    for t in result.transfers:
        c = t.physics_vs_ensemble
        key = f"{t.source}->{t.target}: physics vs ensemble"
        rows.append(
            {
                "train → test": f"{t.source} → {t.target}",
                "ΔMAE kg (ensemble − physics) [95% CI]": f"{c.mae_difference.estimate:+.1f} [{c.mae_difference.low:+.1f}, {c.mae_difference.high:+.1f}]",
                "Wilcoxon p": f"{c.wilcoxon_p:.4g}",
                "Holm p": f"{result.h3_holm[key]:.4g}",
                "verdict": "physics better" if c.a_better else ("ensemble better" if c.b_better else "no claimable difference"),
            }
        )
    out += [_md_table(rows), ""]

    out += ["### H3d: both herds pooled (grouped CV, scored per herd)", ""]
    rows = [
        {
            "scored on": HERD_NAMES.get(h, h),
            "n": int(m["n"]),
            "MAE kg": f"{m['mae']:.1f}",
            "MAPE %": f"{m['mape']:.2f}",
            "bias kg": f"{m['bias']:+.1f}",
            "max |err|": f"{m['max_abs']:.0f}",
            "R²": f"{m['r2']:.2f}",
        }
        for h, m in result.pooled.items()
    ]
    out += [_md_table(rows), ""]

    out += [
        "## H4: 90% conformal intervals",
        "",
        "Calibrated on 30 random animals (within herd) or on the 20 reference animals after "
        "recalibration (transfer); coverage measured on the remaining animals, 500 draws.",
        "",
    ]
    rows = []
    for herd, r in result.herds.items():
        c = r.conformal
        rows.append({"setting": f"within {HERD_NAMES[herd]}", "coverage [95% range]": f"{c[0]:.3f} [{c[1]:.3f}, {c[2]:.3f}]", "half-width kg": f"{c[3]:.1f}"})
    for t in result.transfers:
        c = t.recalibrated_conformal
        rows.append({"setting": f"{t.source} → {t.target}, k = 20", "coverage [95% range]": f"{c[0]:.3f} [{c[1]:.3f}, {c[2]:.3f}]", "half-width kg": f"{c[3]:.1f}"})
    out += [_md_table(rows), ""]
    return "\n".join(out)


def audit_markdown(audit: JoinAudit, control: JoinAudit | None = None) -> str:
    seg = ", ".join(f"files from {f}: row = file {o:+d}" for f, o in audit.segments)
    return "\n".join(
        [
            "# CowDatabase file-to-row join audit",
            "",
            "Generated by `cattle3d audit-join`. Do not edit by hand.",
            "",
            "The public release pairs cloud file N with table row N. The captures and the table "
            "rows are both in time order, so the correct pairing is a monotone alignment with "
            "occasional gaps. It was computed from **heights only** (extracted top/side heights "
            "against manual withers and hip heights). Weight was not used to build the join; it is "
            "shown below only as an independent check.",
            "",
            "| | published join | audited join |",
            "|---|---|---|",
            f"| height agreement (corr) | {audit.height_corr_published:.3f} | {audit.height_corr_audited:.3f} |",
            f"| weight vs trunk volume (corr), not used for the join | {audit.weight_volume_corr_published:.3f} | {audit.weight_volume_corr_audited:.3f} |",
            "",
            f"Runs found: {seg}.",
            "",
            f"Rows without a capture: {', '.join(audit.unmatched_rows) or 'none'}. "
            f"Files without a row: {', '.join(audit.unmatched_files) or 'none'}. "
            f"{len(audit.mapping)} animals keep a label.",
            "",
        ]
        + (
            [
                "",
                "## Control: CowDatabase2",
                "",
                "CowDatabase2 joins clouds to rows by the recorded frame number, so its join is "
                "known to be right. The same procedure applied to it should not improve the "
                "independent weight check.",
                "",
                "| | recorded join | alignment result |",
                "|---|---|---|",
                f"| height agreement (corr) | {control.height_corr_published:.3f} | {control.height_corr_audited:.3f} |",
                f"| weight vs trunk volume (corr) | {control.weight_volume_corr_published:.3f} | {control.weight_volume_corr_audited:.3f} |",
                "",
                f"Runs found: {', '.join(f'from {f}: {o:+d}' for f, o in control.segments)}.",
            ]
            if control is not None
            else []
        )
    )


def write_figures(result: StudyResult, out_dir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []

    fig, axes = plt.subplots(1, len(result.herds), figsize=(11, 5))
    for ax, (herd, r) in zip(np.atleast_1d(axes), result.herds.items()):
        pred = r.oof[ENSEMBLE]
        ax.scatter(r.weight_kg, pred, s=14, alpha=0.75)
        lo, hi = r.weight_kg.min() - 20, r.weight_kg.max() + 20
        ax.plot([lo, hi], [lo, hi], color="grey", lw=1)
        m = metrics(r.weight_kg, pred)
        ax.set_title(f"{HERD_NAMES[herd]}\nMAE {m.mae:.1f} kg, MAPE {m.mape:.2f} %", fontsize=10)
        ax.set_xlabel("scale weight, kg")
        ax.set_ylabel("predicted (out-of-fold), kg")
    fig.tight_layout()
    paths.append(out_dir / "within_herd_oof.png")
    fig.savefig(paths[-1], dpi=130)
    plt.close(fig)

    fig, axes = plt.subplots(1, len(result.transfers), figsize=(11, 4.5))
    for ax, t in zip(np.atleast_1d(axes), result.transfers):
        for mode, style in (("intercept", "-o"), ("intercept+slope", "--s")):
            pts = [p for p in t.recalibration if p.mode == mode]
            ks = [p.k for p in pts]
            ax.plot(ks, [p.mape_mean for p in pts], style, label=f"correction: {mode}")
            ax.fill_between(ks, [p.mape_low for p in pts], [p.mape_high for p in pts], alpha=0.15)
        ax.axhline(t.within_target_mape, color="grey", lw=1, label="within-herd CV")
        ax.axhline(t.within_target_mape + H3B_MARGIN_MAPE, color="grey", lw=1, ls=":", label="margin")
        ax.set_title(f"{t.source} → {t.target}", fontsize=10)
        ax.set_xlabel("reference weighings k")
        ax.set_ylabel("MAPE, %")
        ax.legend(fontsize=8)
    fig.tight_layout()
    paths.append(out_dir / "recalibration_curve.png")
    fig.savefig(paths[-1], dpi=130)
    plt.close(fig)

    fig, axes = plt.subplots(1, len(result.transfers), figsize=(11, 5))
    for ax, t in zip(np.atleast_1d(axes), result.transfers):
        yt = result.herds[t.target].weight_kg
        for name, pred in t.zero_shot.items():
            ax.scatter(yt, pred, s=10, alpha=0.6, label=name)
        lo, hi = yt.min() - 30, yt.max() + 30
        ax.plot([lo, hi], [lo, hi], color="grey", lw=1)
        ax.set_title(f"zero-shot {t.source} → {t.target}", fontsize=10)
        ax.set_xlabel("scale weight, kg")
        ax.set_ylabel("predicted, kg")
        ax.legend(fontsize=7)
    fig.tight_layout()
    paths.append(out_dir / "zero_shot_transfer.png")
    fig.savefig(paths[-1], dpi=130)
    plt.close(fig)
    return paths
